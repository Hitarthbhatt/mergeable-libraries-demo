#!/usr/bin/env python3
"""Generates CoreKit's "shared code" so the module has a realistic API surface.

Real shared modules collect hundreds of analytics constants and dozens of
models. Typing those by hand is boring, so we generate them.

    python3 scripts/generate_corekit.py --access public    # default, what the app uses
    python3 scripts/generate_corekit.py --access internal  # for the public-vs-internal experiment

Everything stays reachable through `CoreKitCatalog`, so in the internal
variant the code is still alive. Only the *access level* changes.
"""
import argparse
import pathlib

EVENT_GROUPS = ["Home", "Search", "Catalog", "Cart", "Checkout", "Orders",
                "Profile", "Support", "Wishlist", "Notifications", "Onboarding", "Settings"]
EVENTS_PER_GROUP = 30
MODEL_COUNT = 40
FIELDS = [("id", "String"), ("title", "String"), ("subtitle", "String"),
          ("imageURL", "String"), ("price", "Double"), ("quantity", "Int"),
          ("isActive", "Bool"), ("createdAt", "Double")]

OUT = pathlib.Path(__file__).resolve().parent.parent / "Modules/CoreKit/Sources/Generated"


def events(acl: str) -> str:
    lines = ["// Generated by scripts/generate_corekit.py. Do not edit.", "",
             f"{acl}enum AnalyticsEvent {{"]
    for group in EVENT_GROUPS:
        lines.append(f"    {acl}enum {group} {{")
        for i in range(EVENTS_PER_GROUP):
            lines.append(f'        {acl}static let event{i:02d} = "{group} Event {i:02d}"')
        lines.append("    }")
    lines.append("}")
    lines += ["", "extension AnalyticsEvent {", f"    {acl}static var all: [String] {{", "        ["]
    for group in EVENT_GROUPS:
        for i in range(EVENTS_PER_GROUP):
            lines.append(f"            {group}.event{i:02d},")
    lines += ["        ]", "    }", "}", ""]
    return "\n".join(lines)


def models(acl: str) -> str:
    lines = ["// Generated by scripts/generate_corekit.py. Do not edit.", ""]
    for m in range(MODEL_COUNT):
        name = f"Model{m:02d}"
        lines.append(f"{acl}struct {name}: Codable, Equatable, Hashable {{")
        for field, type_ in FIELDS:
            lines.append(f"    {acl}var {field}: {type_}")
        params = ", ".join(f"{f}: {t}" for f, t in FIELDS)
        lines.append(f"    {acl}init({params}) {{")
        for field, _ in FIELDS:
            lines.append(f"        self.{field} = {field}")
        lines += ["    }", "",
                  f"    {acl}var displayTitle: String {{ \"\\(title) - \\(subtitle)\" }}",
                  f"    {acl}var formattedPrice: String {{ \"\\(price * Double(quantity))\" }}",
                  "}", ""]
    lines += ["extension CoreKitCatalog {", f"    {acl}static func sampleModels() -> [any Hashable] {{", "        ["]
    for m in range(MODEL_COUNT):
        lines.append(f'            Model{m:02d}(id: "{m}", title: "t", subtitle: "s", imageURL: "u", '
                     f"price: {m}.0, quantity: {m}, isActive: true, createdAt: 0),")
    lines += ["        ]", "    }", "}", ""]
    return "\n".join(lines)


def catalog(acl: str) -> str:
    return "\n".join([
        "// Generated by scripts/generate_corekit.py. Do not edit.", "",
        "// The one door that is always public, so nothing gets dead-stripped",
        "// in the internal variant of the experiment.",
        "public enum CoreKitCatalog {",
        "    public static func touchEverything() -> Int {",
        "        AnalyticsEvent.all.count + sampleModels().count",
        "    }",
        "}", ""])


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--access", choices=["public", "internal"], default="public")
    args = parser.parse_args()
    acl = "public " if args.access == "public" else ""

    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "AnalyticsEvent+Generated.swift").write_text(events(acl))
    (OUT / "Models+Generated.swift").write_text(models(acl))
    (OUT / "CoreKitCatalog.swift").write_text(catalog(acl))
    print(f"CoreKit generated with {args.access} access in {OUT}")


if __name__ == "__main__":
    main()
